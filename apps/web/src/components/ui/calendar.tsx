import { Button, buttonVariants } from "@/components/ui/button"
import { ChevronLeftIcon, ChevronRightIcon, ChevronDownIcon, CheckIcon } from "lucide-react"

function CalendarDropdown({
  options,
  value,
  onChange,
  disabled,
  "aria-label": ariaLabel,
}: {
  options?: { value: number; label: string; disabled: boolean }[];
  value?: string | number | readonly string[];
  onChange?: (e: React.ChangeEvent<HTMLSelectElement>) => void;
  disabled?: boolean;
  "aria-label"?: string;
}) {
  const [isOpen, setIsOpen] = React.useState(false);
  const wrapperRef = React.useRef<HTMLDivElement>(null);

  React.useEffect(() => {
    const handleClickOutside = (event: MouseEvent) => {
      if (wrapperRef.current && !wrapperRef.current.contains(event.target as Node)) {
        setIsOpen(false);
      }
    };
    document.addEventListener("mousedown", handleClickOutside);
    return () => document.removeEventListener("mousedown", handleClickOutside);
  }, []);

  const selectedOption = options?.find((opt) => opt.value.toString() === value?.toString());

  return (
    <div ref={wrapperRef} className="relative flex items-center min-w-[80px]">
      <button
        type="button"
        disabled={disabled}
        onClick={() => setIsOpen(!isOpen)}
        className="flex h-8 w-full items-center justify-between gap-1.5 rounded-lg border border-[#E2D9D2] bg-white py-1 pr-2 pl-2.5 text-xs font-semibold text-[var(--text-main)] hover:border-[var(--primary-color)] transition-all duration-300 cursor-pointer outline-none shadow-xs"
        aria-label={ariaLabel}
      >
        <span>{selectedOption ? selectedOption.label : value}</span>
        <ChevronDownIcon className="size-3.5 text-[var(--text-light)] shrink-0 transition-transform duration-200" />
      </button>

      {isOpen && (
        <div 
          data-lenis-prevent
          onWheel={(e) => e.stopPropagation()}
          onTouchMove={(e) => e.stopPropagation()}
          className="absolute top-full left-0 mt-1 z-[60] max-h-60 overflow-y-auto min-w-[120px] rounded-lg bg-[var(--bg-main)] text-[var(--text-main)] shadow-md border border-[#E2D9D2] py-1 animate-in fade-in-0 zoom-in-95 duration-100"
        >
          {options?.map((option) => (
            <button
              key={option.value}
              type="button"
              disabled={option.disabled}
              onClick={() => {
                if (onChange) {
                  const syntheticEvent = {
                    target: { value: option.value.toString() }
                  } as React.ChangeEvent<HTMLSelectElement>;
                  onChange(syntheticEvent);
                }
                setIsOpen(false);
              }}
              className="relative flex w-full cursor-pointer items-center justify-between gap-2 rounded-sm py-1.5 pr-8 pl-3 text-xs outline-none select-none hover:bg-[var(--primary-color)] hover:text-white disabled:pointer-events-none disabled:opacity-50 text-left font-medium group"
            >
              <span>{option.label}</span>
              {option.value.toString() === value?.toString() && (
                <CheckIcon className="absolute right-2 size-3.5 text-[var(--primary-color)] group-hover:text-white" />
              )}
            </button>
          ))}
        </div>
      )}
    </div>
  );
}

